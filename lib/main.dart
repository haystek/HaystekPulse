import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'firebase_options_dev.dart';
import 'package:flutter/services.dart' show appFlavor;
import 'screens/auth_gate.dart';
import 'screens/update_gate.dart';
import 'services/error_log.dart';
import 'services/notification_service.dart';
import 'theme/app_theme.dart';
import 'services/schedule_service.dart';
Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(
    // Dev build -> haystek-pulse-dev, otherwise live (haystek-pulse).
    options: appFlavor == 'dev'
        ? DevFirebaseOptions.currentPlatform
        : DefaultFirebaseOptions.currentPlatform,
  );
  // If something breaks: save only the error and app version (no phone details).
  await ErrorLog.start();
  await ScheduleService.start();
  runApp(const HaystekApp());
}

class HaystekApp extends StatelessWidget {
  const HaystekApp({super.key});

  @override
  Widget build(BuildContext context) {
    final base = buildAppTheme();
    return MaterialApp(
      title: 'Haystek Pulse',
      debugShowCheckedModeBanner: false,
      navigatorKey: NotificationService.navigatorKey,
      scaffoldMessengerKey: NotificationService.messengerKey,

      // Inter on every screen, whatever font style the phone uses.
      theme: base.copyWith(
        textTheme: GoogleFonts.interTextTheme(base.textTheme),
        primaryTextTheme: GoogleFonts.interTextTheme(base.primaryTextTheme),
      ),

      // Same text size on every phone, whatever its font size setting.
      builder: (context, child) {

        final page = MediaQuery(
          data: MediaQuery.of(context).copyWith(
            textScaler: TextScaler.noScaling,
          ),
          child: child!,
        );
        // DEV build: an orange "DEV" ribbon on every screen, so a test
        // app is never mistaken for the live one.
        if (appFlavor != 'dev') return page;
        return Banner(
          message: 'DEV',
          location: BannerLocation.topEnd,
          color: const Color(0xFFE8572A),
          child: page,
        );
      },

      // Too-old builds see "Please update" (settings/app in Firestore).
      home: const UpdateGate(child: AuthGate()),
    );
  }
}
